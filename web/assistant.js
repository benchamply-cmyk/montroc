/* L'assistant du site : une bulle en bas à droite qui répond aux questions sur TopTroc (API /assistant, Claude).
   Il ne voit ni le compte ni les objets du membre : la conversation reste dans cet onglet (sessionStorage) et
   n'est envoyée qu'à l'API, sans jeton de connexion. Chargé par site.js sur toutes les pages, dans les trois langues :
   ses textes sont ici, pas dans le catalogue de traduction. */
(()=>{
  const API=window.TT_API; if(!API||document.getElementById('assistant'))return;
  const lang=window.TT_I18N?.lang||'fr';
  const T={
    fr:{ouvrir:"Une question ? Demandez à l'assistant",fermer:"Fermer l'assistant",titre:'Assistant TopTroc',sous:'Réponses instantanées sur le troc',
      bonjour:"Bonjour ! Je réponds à vos questions sur TopTroc : le Match, le Grand Troc, Troc Premium, comment publier un objet… Que voulez-vous savoir ?",
      idees:["Comment marche le Grand Troc ?","Est-ce vraiment gratuit ?","Comment publier un objet ?"],
      champ:'Votre question…',envoyer:'Envoyer',attente:"L'assistant écrit…",reveil:"Le serveur se réveille, encore quelques secondes…",
      avis:"Réponses générées par une IA, qui peut se tromper. Ne partagez pas d'informations personnelles.",
      panne:"L'assistant n'est pas disponible pour l'instant. Les réponses courantes sont dans la [FAQ](/faq/), et l'équipe répond à contact@toptroc.com.",
      effacer:'Nouvelle conversation'},
    en:{ouvrir:'Got a question? Ask the assistant',fermer:'Close the assistant',titre:'TopTroc assistant',sous:'Instant answers about swapping',
      bonjour:"Hello! I answer your questions about TopTroc: the Match, the Grand Troc, Troc Premium, how to post an item… What would you like to know?",
      idees:['How does the Grand Troc work?','Is it really free?','How do I post an item?'],
      champ:'Your question…',envoyer:'Send',attente:'The assistant is typing…',reveil:'The server is waking up, a few more seconds…',
      avis:'Answers are generated by an AI and may contain mistakes. Do not share personal information.',
      panne:'The assistant is not available right now. Common answers are in the [FAQ](/faq/), and the team replies at contact@toptroc.com.',
      effacer:'New conversation'},
    es:{ouvrir:'¿Una pregunta? Pregunta al asistente',fermer:'Cerrar el asistente',titre:'Asistente TopTroc',sous:'Respuestas al instante sobre el trueque',
      bonjour:'¡Hola! Respondo a tus preguntas sobre TopTroc: el Match, el Grand Troc, Troc Premium, cómo publicar un objeto… ¿Qué quieres saber?',
      idees:['¿Cómo funciona el Grand Troc?','¿Es realmente gratis?','¿Cómo publico un objeto?'],
      champ:'Tu pregunta…',envoyer:'Enviar',attente:'El asistente está escribiendo…',reveil:'El servidor se está despertando, unos segundos más…',
      avis:'Respuestas generadas por una IA, que puede equivocarse. No compartas información personal.',
      panne:'El asistente no está disponible por ahora. Las respuestas habituales están en las [preguntas frecuentes](/faq/), y el equipo responde en contact@toptroc.com.',
      effacer:'Nueva conversación'}
  }[lang]||{};
  const CLE='tt.assistant';
  const lire=()=>{try{const v=JSON.parse(sessionStorage.getItem(CLE));return Array.isArray(v)?v:[]}catch{return []}};
  const garder=()=>{try{sessionStorage.setItem(CLE,JSON.stringify(fil.slice(-30)))}catch{}};
  let fil=lire(), enCours=false;
  const esc=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const local=p=>window.TT_I18N?TT_I18N.localPath(p):p;
  // Seuls les liens vers le site lui-même et l'adresse de contact deviennent cliquables.
  function rendu(texte){
    let h=esc(texte)
      .replace(/\[([^\]]{1,80})\]\((\/[A-Za-z0-9\-/#=?]*)\)/g,(_,t,p)=>`<a href="${esc(local(p))}">${t}</a>`)
      .replace(/\bcontact@toptroc\.com\b/g,'<a href="mailto:contact@toptroc.com">contact@toptroc.com</a>')
      .replace(/\*\*([^*]{1,120})\*\*/g,'<strong>$1</strong>');
    return h.split(/\n{2,}/).map(par=>{
      const lignes=par.split('\n');
      if(lignes.every(l=>/^\s*(?:[-•*]|\d+\.)\s/.test(l)))return '<ul>'+lignes.map(l=>'<li>'+l.replace(/^\s*(?:[-•*]|\d+\.)\s/,'')+'</li>').join('')+'</ul>';
      return '<p>'+lignes.join('<br>')+'</p>';
    }).join('');
  }
  const ICONE='<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 5.5A2.5 2.5 0 0 1 6.5 3h11A2.5 2.5 0 0 1 20 5.5v8a2.5 2.5 0 0 1-2.5 2.5H10l-4.5 4v-4h0A1.5 1.5 0 0 1 4 14.5z"/><path d="M8.5 9.5h.01M12 9.5h.01M15.5 9.5h.01"/></svg>';
  const CROIX='<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18"/></svg>';
  const zone=document.createElement('div'); zone.id='assistant'; zone.className='assistant'; zone.hidden=true;
  zone.innerHTML=`
    <section class="assistant-fenetre" id="assistant-fenetre" role="dialog" aria-modal="false" aria-labelledby="assistant-titre" hidden>
      <header class="assistant-tete">
        <span class="assistant-avatar">${ICONE}</span>
        <div><strong id="assistant-titre">${esc(T.titre)}</strong><small>${esc(T.sous)}</small></div>
        <button type="button" class="assistant-nouveau" data-effacer title="${esc(T.effacer)}" aria-label="${esc(T.effacer)}"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 12a8 8 0 1 0 2.4-5.7M4 4v4h4"/></svg></button>
        <button type="button" class="assistant-x" data-fermer aria-label="${esc(T.fermer)}">${CROIX}</button>
      </header>
      <div class="assistant-fil" role="log" aria-live="polite"></div>
      <div class="assistant-idees"></div>
      <form class="assistant-champ">
        <textarea name="q" rows="1" maxlength="1000" placeholder="${esc(T.champ)}" aria-label="${esc(T.champ)}"></textarea>
        <button type="submit" aria-label="${esc(T.envoyer)}"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13M13 6l6 6-6 6"/></svg></button>
      </form>
      <p class="assistant-avis">${esc(T.avis)}</p>
    </section>
    <button type="button" class="assistant-bulle" aria-controls="assistant-fenetre" aria-expanded="false" aria-label="${esc(T.ouvrir)}" title="${esc(T.ouvrir)}">${ICONE}${CROIX}</button>`;
  document.body.append(zone);
  const $=s=>zone.querySelector(s);
  const bulle=$('.assistant-bulle'), fenetre=$('.assistant-fenetre'), filEl=$('.assistant-fil'), idees=$('.assistant-idees'), form=$('form'), champ=form.q;

  function message(role,texte,classe=''){
    const d=document.createElement('div'); d.className=`assistant-msg ${role==='user'?'moi':'bot'} ${classe}`;
    if(role==='user')d.textContent=texte; else d.innerHTML=rendu(texte);
    filEl.append(d); filEl.scrollTop=filEl.scrollHeight; return d;
  }
  function afficher(){
    filEl.replaceChildren(); message('assistant',T.bonjour);
    fil.forEach(m=>message(m.role,m.contenu));
    idees.replaceChildren();
    if(!fil.length)T.idees.forEach(q=>{const b=document.createElement('button');b.type='button';b.textContent=q;b.onclick=()=>poser(q);idees.append(b)});
  }
  function ouvrir(oui){
    fenetre.hidden=!oui; bulle.setAttribute('aria-expanded',String(oui)); zone.classList.toggle('ouvert',oui);
    if(oui){afficher();setTimeout(()=>champ.focus(),50)}
  }
  async function poser(q){
    q=q.trim(); if(!q||enCours)return;
    enCours=true; idees.replaceChildren(); champ.value=''; ajuster();
    fil.push({role:'user',contenu:q.slice(0,1000)}); garder(); message('user',q);
    const attente=message('assistant',T.attente,'attente');
    const lent=setTimeout(()=>{attente.innerHTML=rendu(T.reveil)},8000);
    // L'API garde au plus 20 messages, en commençant par une question.
    let envoi=fil.slice(-19); while(envoi.length&&envoi[0].role!=='user')envoi=envoi.slice(1);
    try{
      const r=await fetch(API+'/assistant',{method:'POST',headers:{'Content-Type':'application/json'},
        body:JSON.stringify({messages:envoi,langue:lang,page:location.pathname})});
      const data=await r.json().catch(()=>({}));
      attente.remove();
      if(r.ok&&data.reponse){fil.push({role:'assistant',contenu:data.reponse.slice(0,4000)});garder();message('assistant',data.reponse)}
      else{
        // Question non traitée : on la retire du fil pour pouvoir la reposer.
        fil.pop(); garder();
        message('assistant',r.status===429&&typeof data.detail==='string'&&lang==='fr'?data.detail:T.panne,'erreur');
      }
    }catch{attente.remove();fil.pop();garder();message('assistant',T.panne,'erreur')}
    finally{clearTimeout(lent);enCours=false}
  }
  function ajuster(){champ.style.height='auto';champ.style.height=Math.min(champ.scrollHeight,120)+'px'}
  champ.addEventListener('input',ajuster);
  champ.addEventListener('keydown',e=>{if(e.key==='Enter'&&!e.shiftKey&&!e.isComposing){e.preventDefault();poser(champ.value)}});
  form.onsubmit=e=>{e.preventDefault();poser(champ.value)};
  bulle.onclick=()=>ouvrir(fenetre.hidden);
  $('[data-fermer]').onclick=()=>{ouvrir(false);bulle.focus()};
  $('[data-effacer]').onclick=()=>{fil=[];garder();afficher();champ.focus()};
  zone.addEventListener('keydown',e=>{if(e.key==='Escape'&&!fenetre.hidden){e.stopPropagation();ouvrir(false);bulle.focus()}});
  // Un lien du site dans une réponse : la fenêtre se ferme pour laisser voir la page.
  filEl.addEventListener('click',e=>{if(e.target.closest('a[href^="/"]'))ouvrir(false)});

  // Au-dessus de la barre d'onglets des membres connectés (accueil, mobile).
  const onglets=document.querySelector('nav.tabs');
  const placer=()=>{const h=onglets&&!onglets.hidden&&onglets.offsetParent!==null?onglets.offsetHeight:0;zone.style.setProperty('--assistant-bas',h+'px')};
  if(onglets){new MutationObserver(placer).observe(onglets,{attributes:true,attributeFilter:['hidden','style','class']});addEventListener('resize',placer)}
  placer();

  // La bulle ne s'affiche que si l'API dit l'assistant configuré. Serveur endormi (Render gratuit) : elle apparaît au réveil.
  fetch(API+'/assistant').then(r=>r.ok?r.json():{actif:false}).then(e=>{zone.hidden=!e.actif}).catch(()=>{});
})();
